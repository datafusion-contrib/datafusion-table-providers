impl CassandraTable {
    fn create_federated_table_source(
        self: Arc<Self>,
    ) -> DataFusionResult<Arc<dyn FederatedTableSource>> {
        let table_reference = self.table_reference.clone();
        let schema = Arc::clone(&self.schema);
        let fed_provider = Arc::new(SQLFederationProvider::new(self));
        Ok(Arc::new(SQLTableSource::new_with_schema(
            fed_provider,
            RemoteTableRef::from(table_reference),
            schema,
        )))
    }

    /// Wraps the table in a provider that takes part in federation. Outside of a federated
    /// session, it scans the table like the `CassandraTable` itself.
    ///
    /// # Errors
    ///
    /// Returns an error if the federated table source cannot be created.
    pub fn create_federated_table_provider(
        self: Arc<Self>,
    ) -> DataFusionResult<FederatedTableProviderAdaptor> {
        let table_source = Self::create_federated_table_source(Arc::clone(&self))?;
        Ok(FederatedTableProviderAdaptor::new_with_provider(
            table_source,
            self,
        ))
    }
}

#[async_trait]
impl SQLExecutor for CassandraTable {
    fn name(&self) -> &str {
        "cassandra"
    }

    fn compute_context(&self) -> Option<String> {
        match self.pool.join_push_down() {
            JoinPushDown::Disallow => Some(format!("{}", std::ptr::from_ref(self) as usize)),
            JoinPushDown::AllowedFor(s) => Some(s),
        }
    }

    fn dialect(&self) -> Arc<dyn Dialect> {
        Arc::new(DefaultDialect {})
    }

    fn logical_optimizer(&self) -> Option<LogicalOptimizer> {
        let planner: Arc<dyn FederationPlanner> = Arc::new(CassandraScanPlanner {
            table_reference: self.table_reference.clone(),
            pool: Arc::clone(&self.pool),
            schema: Arc::clone(&self.schema),
        });
        Some(Box::new(move |plan| {
            federate_table_scans_only(plan, Arc::clone(&planner))
        }))
    }

    /// Runs `query` as CQL.
    ///
    /// The federated scans are planned by [`CassandraScanPlanner`] instead, so no SQL
    /// generated by the federation reaches Cassandra.
    fn execute(
        &self,
        query: &str,
        schema: SchemaRef,
        _filters: &[Arc<dyn PhysicalExpr>],
    ) -> DataFusionResult<SendableRecordBatchStream> {
        let cql = query.to_string();
        let conn = self.pool.connect_direct();
        let stream_schema = Arc::clone(&schema);
        let stream = futures::stream::once(async move {
            conn.query_arrow(&cql, &[], Some(stream_schema))
                .await
                .map_err(DataFusionError::External)
        })
        .try_flatten();
        Ok(Box::pin(RecordBatchStreamAdapter::new(schema, stream)))
    }

    async fn table_names(&self) -> DataFusionResult<Vec<String>> {
        Err(DataFusionError::NotImplemented(
            "table inference not implemented".to_string(),
        ))
    }

    async fn get_table_schema(&self, table_name: &str) -> DataFusionResult<SchemaRef> {
        self.pool
            .connect_direct()
            .get_schema(&TableReference::from(table_name))
            .await
            .map_err(|e| DataFusionError::External(Box::new(e)))
    }
}

/// Replaces a federated sub-plan with the same plan in which only the table scans are
/// federated, to be planned by `planner`, as CQL can run nothing more (see the module
/// documentation).
///
/// The projections and limits are pushed down to the scans first: once federated, the scans
/// are opaque to the DataFusion optimizer.
fn federate_table_scans_only(
    plan: LogicalPlan,
    planner: Arc<dyn FederationPlanner>,
) -> DataFusionResult<LogicalPlan> {
    let LogicalPlan::Extension(Extension { node }) = &plan else {
        return Ok(plan);
    };
    let Some(federated) = node.as_any().downcast_ref::<FederatedPlanNode>() else {
        return Ok(plan);
    };

    let optimizer = Optimizer::with_rules(vec![
        Arc::new(OptimizeProjections::new()),
        Arc::new(PushDownLimit::new()),
    ]);
    let inner = optimizer.optimize(
        federated.plan().clone(),
        &OptimizerContext::new(),
        |_, _| {},
    )?;

    inner
        .transform_up_with_subqueries(|plan| match plan {
            LogicalPlan::TableScan(_) => Ok(Transformed::yes(LogicalPlan::Extension(Extension {
                node: Arc::new(FederatedPlanNode::new(plan, Arc::clone(&planner))),
            }))),
            _ => Ok(Transformed::no(plan)),
        })
        .map(|transformed| transformed.data)
}

/// Plans a federated scan of a Cassandra table as a [`CassandraExec`].
///
/// The SQL federation would plan it as a scan that claims all the filters DataFusion pushes
/// down to it at runtime, but CQL can't run them.
struct CassandraScanPlanner {
    table_reference: TableReference,
    pool: Arc<CassandraConnectionPool>,
    schema: SchemaRef,
}

#[async_trait]
impl FederationPlanner for CassandraScanPlanner {
    async fn plan_federation(
        &self,
        node: &FederatedPlanNode,
        _session_state: &dyn Session,
    ) -> DataFusionResult<Arc<dyn ExecutionPlan>> {
        let scan = match node.plan() {
            LogicalPlan::TableScan(scan @ TableScan { filters, .. }) if filters.is_empty() => scan,
            plan => {
                return Err(DataFusionError::Plan(format!(
                    "Cassandra can only run plain table scans, not:\n{plan}"
                )))
            }
        };
        Ok(Arc::new(CassandraExec::try_new(
            self.table_reference.clone(),
            Arc::clone(&self.pool),
            &self.schema,
            scan.projection.as_ref(),
            scan.fetch,
        )?))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use datafusion::arrow::datatypes::{DataType, Field, Schema};
    use datafusion::logical_expr::{col, lit, LogicalPlanBuilder, LogicalTableSource};

    struct NoPlanner;

    #[async_trait]
    impl FederationPlanner for NoPlanner {
        async fn plan_federation(
            &self,
            _node: &FederatedPlanNode,
            _session_state: &dyn Session,
        ) -> DataFusionResult<Arc<dyn ExecutionPlan>> {
            unimplemented!()
        }
    }

    fn federated(plan: LogicalPlan) -> LogicalPlan {
        LogicalPlan::Extension(Extension {
            node: Arc::new(FederatedPlanNode::new(plan, Arc::new(NoPlanner))),
        })
    }

    #[test]
    fn federates_only_the_scans_with_projection_and_limit() {
        let schema = Arc::new(Schema::new(vec![
            Field::new("id", DataType::Int32, true),
            Field::new("name", DataType::Utf8, true),
            Field::new("age", DataType::Int32, true),
        ]));
        let scan = |name| {
            LogicalPlanBuilder::scan(
                TableReference::partial("ks", name),
                Arc::new(LogicalTableSource::new(Arc::clone(&schema))),
                None,
            )
            .unwrap()
        };
        let plan = scan("users")
            .filter(col("age").gt(lit(30)))
            .unwrap()
            .join_on(
                scan("pets").limit(0, Some(5)).unwrap().build().unwrap(),
                datafusion::logical_expr::JoinType::Inner,
                vec![col("ks.users.id").eq(col("ks.pets.id"))],
            )
            .unwrap()
            .project(vec![col("ks.users.name"), col("ks.pets.name")])
            .unwrap()
            .build()
            .unwrap();

        let rewritten =
            federate_table_scans_only(federated(plan.clone()), Arc::new(NoPlanner)).unwrap();
        assert_eq!(rewritten.schema(), plan.schema());
        assert_eq!(
            rewritten.display_indent().to_string(),
            "Projection: ks.users.name, ks.pets.name
  Inner Join:  Filter: ks.users.id = ks.pets.id
    Projection: ks.users.id, ks.users.name
      Filter: ks.users.age > Int32(30)
        Federated
 TableScan: ks.users projection=[id, name, age]
    Limit: skip=0, fetch=5
      Federated
 TableScan: ks.pets projection=[id, name], fetch=5"
        );
    }

    #[test]
    fn keeps_other_plans() {
        let plan = LogicalPlanBuilder::empty(false).build().unwrap();
        assert_eq!(
            federate_table_scans_only(plan.clone(), Arc::new(NoPlanner)).unwrap(),
            plan
        );
    }
}
